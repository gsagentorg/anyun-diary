import assert from 'node:assert/strict';
import { Capacitor } from '@capacitor/core';
globalThis.window = {};
globalThis.localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };
const { backend, fetchIndex, saveBackendBase } = await import('../src/lib/backend.svelte.ts');
const { audioUrl } = await import('../src/lib/types.ts');
let native = false;
Capacitor.isNativePlatform = () => native;
const object = 'objects/' + 'a'.repeat(64) + '.opus';
const fixture = { generatedAt: 1, timezone: 'Asia/Shanghai', recordings: [{file:'YOUR-RECORDING-HERE', start:1, duration:null, segments:[], clips:[{file:'YOUR-CLIP-HERE', opus:object, title:'YOUR-TITLE-HERE', offsetStart:0, offsetEnd:10, seg:null}]}] };
const calls = [];
globalThis.fetch = async url => { calls.push(url); return Response.json(fixture); };
backend.base = 'https://YOUR-BACKEND-HERE';
await fetchIndex();
assert.equal(calls.at(-1), '/api/catalog');
assert.equal(audioUrl(object), '/api/audio-url?f=' + encodeURIComponent(object));
const last = backend.recordings;
globalThis.fetch = async () => Response.json({recordings:[]});
await fetchIndex();
assert.equal(backend.recordings, last);
assert(backend.error);
native = true;
backend.base = '';
const before = calls.length;
await fetchIndex();
assert.equal(calls.length, before, 'unconfigured shell must not request its own API');
globalThis.fetch = async url => { calls.push(url); return Response.json(fixture); };
saveBackendBase('https://YOUR-BACKEND-HERE/');
await fetchIndex();
assert.equal(calls.at(-1), 'https://YOUR-BACKEND-HERE/api/catalog');
assert.equal(audioUrl(object), 'https://YOUR-BACKEND-HERE/api/audio-url?f=' + encodeURIComponent(object));
assert.equal(audioUrl('YOUR-CLIP-HERE.opus'), 'https://YOUR-BACKEND-HERE/audio/YOUR-CLIP-HERE.opus');
let release;
globalThis.fetch = () => new Promise(resolve => { release = resolve; });
const stale = fetchIndex();
backend.base = '';
await fetchIndex();
release(Response.json({...fixture, recordings: [{...fixture.recordings[0], file:'YOUR-STALE-RECORDING-HERE'}]}));
await stale;
assert.equal(backend.recordings[0].file, fixture.recordings[0].file);
console.log('backend: web same-origin, native runtime catalog/signing URL, validation and unavailable-shell guards passed');
