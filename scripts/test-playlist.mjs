import assert from 'node:assert/strict';
import { tracksInRange, dayStartOf, validRange, buildM3u, buildPls, buildXspf } from '../src/lib/playlist-core.ts';
const lo=dayStartOf('2026-01-02'),hi=dayStartOf('2026-01-04');
const audio=(id,startAt)=>({id,file:id+'.wav',opus:id+' #?.opus',title:id,startAt,duration:30.4,monthId:'2026-01',lyrics:[]});
const audios=[audio('upper',hi),audio('C',lo+86400),audio('lower',lo-1),audio('A',lo),audio('B',lo+1)];
const order=[...audios];const tracks=tracksInRange(audios,lo,hi);
assert.deepEqual(tracks.map(t=>t.audio.id),['A','B','C']);assert.deepEqual(audios,order);
assert.equal(new Set(tracks.map(t=>t.queueEntryId)).size,3);
assert.equal(tracksInRange(audios).length,5);assert.deepEqual(tracksInRange(audios,hi+1),[]);
assert.equal(validRange('2026-01-04','2026-01-02'),false);assert.equal(validRange('bad','2026-01-02'),false);
assert.equal(hi-lo,172800);
const base='https://YOUR-SITE-HERE';const text=buildM3u(tracks,base,'test');
assert(text.includes('#EXTINF:30,A'));assert(text.includes(base+'/api/'+encodeURIComponent(tracks[0].audio.opus)));
assert(buildPls(tracks,base,'test').includes('NumberOfEntries=3'));assert(buildXspf(tracks,base,'<test>').includes('&lt;test&gt;'));
console.log('playlist: independent audio range, IDs, duration and exports passed');
